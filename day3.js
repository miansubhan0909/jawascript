// Day 3: String Concatenation aur Assignment Operators

// String concatenation ka matlab hai do ya zyada strings ko jorna.
let firstName = "Subhan";
let lastName = "Khan";
let fullName = firstName + " " + lastName;
console.log("Mera naam " + fullName + " hai.");

// Assignment operator (=) value ko variable mein save karta hai.
let marks = 50;
// Shortcut operators se code chhota aur easy ho jata hai.
marks += 10; // marks mein 10 add: 60
marks -= 5;  // marks mein se 5 minus: 55
marks *= 2;  // marks ko 2 se multiply: 110
marks /= 10; // marks ko 10 se divide: 11

console.log("Mere final marks: " + marks);